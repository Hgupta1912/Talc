import type { LucideIcon } from 'lucide-react'
import {
    ChevronDown,
    Lightbulb,
    RefreshCw,
    Sparkles,
    Target,
    ThumbsUp,
} from 'lucide-react'
import { useEffect, useState } from 'react'
import { ApiError, api } from '../api/client'
import { useApp } from '../store/useApp'
import type { ApiCritiqueSummary } from '../types/api'
import { timeAgo } from '../utils/time'

export const SUMMARY_THRESHOLD = 15

type State =
	| { status: 'loading' }
	| { status: 'none' }
	| { status: 'generating' }
	| { status: 'ready'; summary: ApiCritiqueSummary }
	| { status: 'error'; message: string }

function Group({
	title,
	items,
	icon: Icon,
}: {
	title: string
	items: string[]
	icon: LucideIcon
}) {
	if (items.length === 0) return null
	return (
		<div>
			<h3 className="flex items-center gap-2 text-[13px] font-semibold">
				<Icon size={15} className="text-rust" /> {title}
			</h3>
			<ul className="mt-2 space-y-1.5 pl-6">
				{items.map((item) => (
					<li
						key={item}
						className="list-disc text-[13px] leading-relaxed text-ink/80 marker:text-faint"
					>
						{item}
					</li>
				))}
			</ul>
		</div>
	)
}

export default function CritiqueSummary({
	artworkId,
	commentCount,
}: {
	artworkId: string
	commentCount: number
}) {
	const { token } = useApp()
	const [state, setState] = useState<{ id: string; s: State } | null>(null)
	const [open, setOpen] = useState(false)
	const enough = commentCount >= SUMMARY_THRESHOLD
	const current: State =
		state?.id === artworkId ? state.s : { status: 'loading' }

	const generate = async () => {
		setState({ id: artworkId, s: { status: 'generating' } })
		try {
			const summary = await api<ApiCritiqueSummary>(
				`/artworks/${artworkId}/summary`,
				{ method: 'POST', token },
			)
			setState({ id: artworkId, s: { status: 'ready', summary } })
			setOpen(true)
		} catch (err) {
			setState({
				id: artworkId,
				s: { status: 'error', message: (err as Error).message },
			})
		}
	}

	useEffect(() => {
		if (!token) return
		let cancelled = false
		api<ApiCritiqueSummary>(`/artworks/${artworkId}/summary`, { token })
			.then((summary) => {
				if (!cancelled)
					setState({ id: artworkId, s: { status: 'ready', summary } })
			})
			.catch((err: ApiError) => {
				if (cancelled) return
				setState({
					id: artworkId,
					s:
						err.status === 404
							? { status: 'none' }
							: { status: 'error', message: err.message },
				})
			})
		return () => {
			cancelled = true
		}
	}, [artworkId, token])

	if (current.status === 'loading') return null

	return (
		<section className="mt-16 max-w-[760px] rounded-3xl border border-blush-deep bg-cream p-6">
			<div className="flex items-start justify-between gap-4">
				<div>
					<p className="eyebrow flex items-center gap-1.5">
						<Sparkles size={13} /> Critique summary
					</p>
					<p className="mt-2 text-xs text-muted">
						Only you can see this. Generated by AI from your critiques.
					</p>
				</div>
				{current.status === 'ready' && (
					<div className="flex shrink-0 gap-2">
						{open && commentCount > current.summary.commentCount && (
							<button onClick={generate} className="btn-secondary !py-2">
								<RefreshCw size={14} /> Update
							</button>
						)}
						<button
							onClick={() => setOpen((o) => !o)}
							className="btn-secondary !py-2"
						>
							{open ? 'Hide' : 'Show summary'}
							<ChevronDown
								size={14}
								className={open ? 'rotate-180 transition' : 'transition'}
							/>
						</button>
					</div>
				)}
			</div>

			<div className={current.status === 'ready' && !open ? '' : 'mt-5'}>
				{current.status === 'none' && enough && (
					<div className="flex flex-wrap items-center justify-between gap-3">
						<p className="text-sm text-muted">
							You have {commentCount} critiques. Want an AI summary of what
							people are saying?
						</p>
						<button onClick={generate} className="btn-primary !py-2">
							<Sparkles size={14} /> Generate summary
						</button>
					</div>
				)}

				{current.status === 'none' && !enough && (
					<div>
						<p className="text-sm text-muted">
							Your summary unlocks at {SUMMARY_THRESHOLD} critiques.{' '}
							<span className="font-semibold text-ink">
								{commentCount}/{SUMMARY_THRESHOLD}
							</span>
						</p>
						<div className="mt-3 h-1.5 overflow-hidden rounded-full bg-blush-deep">
							<div
								className="h-full rounded-full bg-accent transition-all"
								style={{
									width: `${Math.min(100, (commentCount / SUMMARY_THRESHOLD) * 100)}%`,
								}}
							/>
						</div>
					</div>
				)}

				{current.status === 'generating' && (
					<div className="space-y-3">
						<p className="text-sm text-muted">Reading your critiques…</p>
						<div className="skeleton h-4 w-3/4 rounded" />
						<div className="skeleton h-4 w-2/3 rounded" />
						<div className="skeleton h-4 w-1/2 rounded" />
					</div>
				)}

				{current.status === 'error' && (
					<div className="flex flex-wrap items-center gap-3">
						<p className="text-sm text-danger">
							Couldn't load the summary: {current.message}
						</p>
						{enough && (
							<button onClick={generate} className="btn-secondary !py-2">
								Try again
							</button>
						)}
					</div>
				)}

				{current.status === 'ready' && open && (
					<div className="space-y-5">
						<Group
							title="Strengths"
							items={current.summary.strengths}
							icon={ThumbsUp}
						/>
						<Group
							title="What to improve"
							items={current.summary.improvements}
							icon={Target}
						/>
						<Group
							title="Suggestions"
							items={current.summary.suggestions}
							icon={Lightbulb}
						/>
						<p className="text-xs text-faint">
							Based on {current.summary.commentCount} critiques ·{' '}
							{timeAgo(current.summary.generatedAt)}
						</p>
					</div>
				)}
			</div>
		</section>
	)
}